/**
 * Проверяет корректность названия города.
 * Удаляет лишние пробелы, проверяет пустоту, допустимые символы и длину.
 *
 * @returns {boolean} true, если название города валидно, иначе false.
 */

export function validateCityName(city) {
  const trimmed = city.trim();

  // Проверяем на пустую строку
  if (!trimmed) {
    console.error("Ошибка: название города не может быть пустым");
    return false;
  }

  // Регулярное выражение для проверки названия города:
  // Позволяет буквы русского и латинского алфавитов, дефисы, пробелы, апострофы, точки
  const cityNamePattern = /^[a-zA-Zа-яА-ЯёЁ\s\-'.]{2,}$/u;

  if (!cityNamePattern.test(trimmed)) {
    console.error("Ошибка: название города содержит недопустимые символы");
    return false;
  }

  // Дополнительно проверим, что нет подряд идущих пробелов или дефисов
  if (/\s{2,}|-{2,}/.test(trimmed)) {
    console.error("Ошибка: название города содержит лишние повторяющиеся пробелы или дефисы");
    return false;
  }

  // Дополнительная проверка длины (например, не менее 2 и не более 50 символов)
  if (trimmed.length < 2 || trimmed.length > 50) {
    console.error("Ошибка: длина названия города должна быть от 2 до 50 символов");
    return false;
  }

  return true;
}